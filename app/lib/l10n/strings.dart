  static Map<String, String> _map(String lang) => switch (lang) {
        'hi' => _hi,
        'kn' => _kn,
        'ml' => _ml,
        _ => _en,
      };

  static String t(String lang, String key, [Map<String, String>? vars]) {
    final raw = _map(lang)[key] ??
        DemoL10n.map(lang)[key] ??
        _en[key] ??
        DemoL10n.map('en')[key] ??
        key;
    if (vars == null || vars.isEmpty) return raw;
    var out = raw;
    vars.forEach((k, v) => out = out.replaceAll('{$k}', v));
    return out;
  }
